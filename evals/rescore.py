"""Score every saved run against the current labels and write evals/results/SUMMARY.md.

    python evals/rescore.py

Saved runs in evals/results/<set>/ are never edited: each keeps the scores computed with the labels of its day. When a
label changes (each change is recorded in the item's note), this summary re-scores every run from its saved answers,
so all runs are compared under the same labels. Model output is not regenerated.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from vea import evaluate, evidence  # noqa: E402

PRICES = {"muse-spark-1.3": (1.25, 4.25)}  # USD per million input / output tokens (dev.meta.ai pricing page)


def rows() -> list[dict]:
    out = []
    for set_dir in sorted((ROOT / "evals" / "results").iterdir()):
        if not set_dir.is_dir():
            continue
        doc = evaluate.load_items(ROOT / "evals" / f"{set_dir.name}.json")
        items = {i["id"]: i for i in doc["items"]}
        package = evidence.load(ROOT / doc["package"])
        for path in sorted(set_dir.glob("*.json")):
            run = json.loads(path.read_text(encoding="utf-8"))
            scored = [evaluate.score_item(package, items[r["id"]], r) for r in run["results"] if r["id"] in items]
            s = evaluate.summarize(scored)
            u = run["usage"]["answering"]
            price = PRICES.get(run.get("model"), (0, 0))
            out.append({"set": set_dir.name, "run": path.stem, "mode": run["mode"], "model": run.get("model"), "n": s["questions"],
                        "accuracy": s["accuracy_pct"], "grounded": s["grounded_accuracy_pct"], "unsafe": s["unsafe_answers"],
                        "refused": s["provider_refusals"], "removed": s["claims_rejected"],
                        "cost": round((u["prompt_tokens"] * price[0] + u["completion_tokens"] * price[1]) / 1e6, 2)})
    return out


def main() -> None:
    lines = ["# All runs, scored with the current labels", "",
             "Generated by `python evals/rescore.py` from the saved answers in each run; see evals/README.md for what each",
             "run found. Cost is computed from the token counts at the listed prices.", "",
             "| Set | Run | Mode | Model | n | Accuracy | Grounded | Unsafe | Refused by provider | Claims removed | Cost (USD) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows():
        lines.append(f"| {r['set']} | {r['run']} | {r['mode']} | {r['model']} | {r['n']} | {r['accuracy']}% | {r['grounded']}% | "
                     f"{r['unsafe']} | {r['refused']} | {r['removed']} | {r['cost']} |")
    target = ROOT / "evals" / "results" / "SUMMARY.md"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[5:]))


if __name__ == "__main__":
    main()
